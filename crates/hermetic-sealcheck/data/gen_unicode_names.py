#!/usr/bin/env python3
"""Generate unicode_names.txt, the `\\N{...}` name table used by fingerprint.rs.

Not run by the build. Regenerate by hand when moving to a newer Unicode version:

    python3 -I gen_unicode_names.py NameAliases.txt > unicode_names.txt

`NameAliases.txt` must be the UCD file of the same Unicode version as the running
Python's `unicodedata.unidata_version` (https://www.unicode.org/Public/<ver>/ucd/).

Output (UTF-8, one entry per line, sorted by bytes):
    # comment lines
    @<PREFIX>\t<first hex>\t<last hex>   names "<PREFIX><code point as %04X>" in that range
    <NAME>\t<hex>                         a character name or formal alias, upper case
Hangul syllable names are algorithmic and handled in code, so they are not listed.
Every row is checked against Python's own `\\N{...}` decoding.
"""
import sys
import unicodedata

# Tangut ideographs have no `unicodedata.name()` but `\N{TANGUT IDEOGRAPH-XXXXX}` decodes;
# their range is found by probing the Tangut blocks.
TANGUT = "TANGUT IDEOGRAPH-"
TANGUT_PROBE = range(0x17000, 0x19000)

RULE_PREFIXES = [
    TANGUT,
    "CJK UNIFIED IDEOGRAPH-",
    "CJK COMPATIBILITY IDEOGRAPH-",
    "TANGUT IDEOGRAPH-",
    "KHITAN SMALL SCRIPT CHARACTER-",
    "NUSHU CHARACTER-",
    "EGYPTIAN HIEROGLYPH-",
]


def decodes_to(name, cp):
    try:
        return ord(eval('"\\N{' + name + '}"')) == cp
    except (SyntaxError, TypeError, ValueError):
        return False


def main():
    rows = {}
    ranges = {p: [] for p in RULE_PREFIXES}
    for cp in range(0x110000):
        name = unicodedata.name(chr(cp), None)
        if name is None and cp in TANGUT_PROBE and decodes_to(TANGUT + "%04X" % cp, cp):
            name = TANGUT + "%04X" % cp
        if name is None or name.startswith("HANGUL SYLLABLE "):
            continue
        prefix = next((p for p in RULE_PREFIXES if name == p + "%04X" % cp), None)
        if prefix is not None:
            r = ranges[prefix]
            if r and r[-1][1] == cp - 1:
                r[-1][1] = cp
            else:
                r.append([cp, cp])
            continue
        rows[name] = cp
    with open(sys.argv[1], encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            hexcp, alias, _kind = line.split(";")
            cp = int(hexcp, 16)
            if decodes_to(alias, cp):
                rows.setdefault(alias, cp)
    for name, cp in rows.items():
        assert decodes_to(name, cp), name
    out = sys.stdout
    out.write("# Unicode %s character names and formal aliases for \\N{...}.\n"
              % unicodedata.unidata_version)
    out.write("# Generated by gen_unicode_names.py from Python %s unicodedata and "
              "NameAliases.txt.\n" % sys.version.split()[0])
    lines = []
    for p, rs in ranges.items():
        for a, b in rs:
            lines.append("@%s\t%X\t%X" % (p, a, b))
    lines.extend("%s\t%X" % (n, cp) for n, cp in rows.items())
    lines.sort(key=lambda s: s.encode("utf-8"))
    out.write("\n".join(lines) + "\n")


main()
